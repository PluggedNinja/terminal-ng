import { useState, useEffect } from 'react';

// ---------------------------------------------------------------------------
// Lightweight i18n store. No external deps: a module-level current language,
// a set of subscribers, and a `t(key)` lookup with {var} interpolation.
// Components subscribe via the useI18n() hook and re-render on language change.
// ---------------------------------------------------------------------------

export const LANGS = ['en', 'pt', 'zh', 'es']; // supported UI languages
export const LANG_LABELS = { en: 'English', pt: 'Português', zh: '中文', es: 'Español' };
export const LANG_SHORT = { en: 'EN', pt: 'PT', zh: '中', es: 'ES' };

const STORAGE_KEY = 'tng_lang';

function detectInitial() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && LANGS.includes(saved)) return saved;
  } catch {}
  try {
    const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    if (LANGS.includes(nav)) return nav;
  } catch {}
  return 'en';
}

let lang = detectInitial();
const subs = new Set();
try { document.documentElement.lang = lang; } catch {}

export function getLang() { return lang; }

export function setLang(l) {
  if (!LANGS.includes(l) || l === lang) return;
  lang = l;
  try { localStorage.setItem(STORAGE_KEY, l); } catch {}
  try { document.documentElement.lang = l; } catch {}
  subs.forEach((fn) => { try { fn(); } catch {} });
}

export function t(key, vars) {
  const table = dict[lang] || dict.en;
  let str = table[key];
  if (str == null) str = dict.en[key];
  if (str == null) return key;
  if (vars) {
    str = str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  }
  return str;
}

export function useI18n() {
  const [, force] = useState(0);
  useEffect(() => {
    const fn = () => force((x) => x + 1);
    subs.add(fn);
    return () => subs.delete(fn);
  }, []);
  return { t, lang, setLang, langs: LANGS };
}

